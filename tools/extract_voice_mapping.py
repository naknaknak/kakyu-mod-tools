"""Extract filename-bearing MES-to-OGG marker references for the Kakyu remake.

The original scripts store references such as ``a018.og``.  Archive files
use four-digit IDs (``A0018.OGG``), while TINA has two voice sets selected by
the original ``[Voice] TINA=1|2`` setting.
"""

from __future__ import annotations

import argparse
import csv
import json
import re
from pathlib import Path


VOICE_REF = re.compile(rb"(?i)([a-z])(\d{3,4})\.og")


def normalize_voice_id(match: re.Match[bytes]) -> str:
    return f"{match.group(1).decode('ascii').upper()}{int(match.group(2)):04d}"


def build_rows(source_root: Path) -> list[dict[str, object]]:
    mes_root = source_root / "mes"
    banks = {
        "voice": ("voice.arc", source_root / "voice"),
        "tina1": ("tina1.arc", source_root / "tina1"),
        "tina2": ("tina2.arc", source_root / "tina2"),
    }
    rows: list[dict[str, object]] = []

    for mes_path in sorted(mes_root.glob("*.MES")):
        data = mes_path.read_bytes()
        for match in VOICE_REF.finditer(data):
            voice_id = normalize_voice_id(match)
            prefix = voice_id[0]
            candidate_sets = ("tina1", "tina2") if prefix == "M" else ("voice",)
            for voice_set in candidate_sets:
                archive, bank_root = banks[voice_set]
                relative_path = f"{voice_set}/{voice_id}.OGG"
                rows.append(
                    {
                        "mes_file": mes_path.name,
                        "mes_offset": f"0x{match.start():x}",
                        "token": match.group(0).decode("ascii"),
                        "voice_id": voice_id,
                        "voice_set": voice_set,
                        "archive": archive,
                        "relative_path": relative_path,
                        "exists_in_extracted_assets": (bank_root / f"{voice_id}.OGG").is_file(),
                    }
                )
    return rows


def write_outputs(rows: list[dict[str, object]], output_dir: Path) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    fields = [
        "mes_file",
        "mes_offset",
        "token",
        "voice_id",
        "voice_set",
        "archive",
        "relative_path",
        "exists_in_extracted_assets",
    ]
    with (output_dir / "mes_voice_mapping.csv").open("w", newline="", encoding="utf-8-sig") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)

    payload = {
        "schema_version": 1,
        "description": "Filename-bearing MES voice markers resolved to extracted OGG candidates.",
        "token_rule": "a018.og -> A0018.OGG; the numeric part is zero-padded to four digits.",
        "voice_sets": {
            "voice": {"setting": None, "archive": "voice.arc", "directory": "voice"},
            "tina1": {"setting": "[Voice] TINA=1", "archive": "tina1.arc", "directory": "tina1"},
            "tina2": {"setting": "[Voice] TINA=2", "archive": "tina2.arc", "directory": "tina2"},
        },
        "rows": rows,
        "statistics": {
            "mapping_rows": len(rows),
            "mes_reference_occurrences": len({(r["mes_file"], r["mes_offset"]) for r in rows}),
            "unique_voice_ids": len({r["voice_id"] for r in rows}),
        },
    }
    (output_dir / "mes_voice_mapping.json").write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

    (output_dir / "README.md").write_text(
        """# MES Voice Mapping

This directory contains filename-bearing voice markers found in the extracted
`ELFIMAGE/mes/*.MES` scripts.

## ID resolution

The scripts use three-digit tokens such as `a018.og`; the extracted archive
files use an uppercase prefix, four-digit number, and `.OGG` extension:

`a018.og` -> `A0018.OGG`

Normal character voices resolve to `voice.arc`. TINA references use the same
`Mxxxx` ID in two alternate voice-actor sets. The original game selects the
set through `ELFIMAGE/AI5WIN.INI`:

```ini
[Voice]
TINA=1
```

Use `tina1` for `TINA=1` and `tina2` for `TINA=2`.

## Files

- `mes_voice_mapping.json`: Godot/runtime-friendly mapping with one row per
  candidate voice set.
- `mes_voice_mapping.csv`: spreadsheet-friendly review table.
- `extract_voice_mapping.py`: reproducible extractor. Run it with the
  original extracted `ELFIMAGE` directory as `--source-root`.

This broad mapping is based on `.og` token discovery. Use
`audit_mes_voice_markers.py` when an exact marker envelope and code-relative
offset are required. Native command `0x07` is a state-write handler, so neither
tool by itself proves the engine playback call path. Any voice IDs generated by
a numeric VM command still need a separate VM-level decoder.
""",
        encoding="utf-8",
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source-root", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    rows = build_rows(args.source_root)
    write_outputs(rows, args.output_dir)
    print(f"wrote {len(rows)} mapping rows to {args.output_dir}")


if __name__ == "__main__":
    main()
